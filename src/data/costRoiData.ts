// Historical Cloud Storage Cost & ROI Telemetry Dataset

export interface MonthlyCostPoint {
  month: string;             // e.g. "Oct '24", "Nov '24"
  fullDate: string;          // e.g. "October 2024"
  costBefore: number;        // Storage bill without compression in USD ($)
  costAfter: number;         // Actual bill paid after CloudOptima lossless compression ($)
  monthlySavings: number;    // costBefore - costAfter ($)
  savingsPercent: number;    // % reduction (e.g. 75)
  cumulativeSavings: number; // Running total of gross savings ($)
  platformCost: number;      // CloudOptima compute & operational cost ($)
  cumulativePlatformCost: number;
  netBenefit: number;        // monthlySavings - platformCost ($)
  cumulativeNetBenefit: number;
  roiPercent: number;        // (cumulativeNetBenefit / cumulativePlatformCost) * 100
  roiMultiplier: number;     // cumulativeSavings / cumulativePlatformCost
  rawVolumeTB: number;       // Raw telemetry volume (Terabytes)
  compressedVolumeTB: number;// Post-compression stored volume (Terabytes)
  compressionRatio: string;  // e.g. "4.1:1"
}

export interface DailyCostPoint {
  date: string;              // e.g. "Aug 08", "Aug 09"
  fullDate: string;          // e.g. "2026-08-08"
  costBefore: number;        // Daily storage cost without compression ($)
  costAfter: number;         // Daily storage cost after compression ($)
  savings: number;           // Daily savings ($)
  savingsPercent: number;    // % reduction
  cumulativeSavings: number; // 30-day running savings ($)
  roiPercent: number;        // Instantaneous ROI %
  rawVolumeGB: number;
  compressedVolumeGB: number;
}

export interface ProviderCostTrend {
  provider: "All" | "AWS" | "Azure" | "GCP" | "Hybrid Cloud";
  costBefore: number;
  costAfter: number;
  savings: number;
  savingsPercent: number;
  totalVolumeTB: number;
  monthlyData: {
    month: string;
    costBefore: number;
    costAfter: number;
    savings: number;
    roiPercent: number;
  }[];
}

